export const DICT = { uz, ru, en };

let cur = "uz";
export const getLang = () => cur;
export const setLang = l => { if (DICT[l]) cur = l; };

const fill = (s, vars) => vars
  ? String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m))
  : String(s);

// kalit topilmasa o'zbekcha (yoki kalitning o'zi) qaytariladi — ilova hech qachon
// bo'sh matn ko'rsatmaydi
export const t = (key, vars) => {
  const pack = DICT[cur] || uz;
  const v = pack[key] !== undefined ? pack[key] : uz[key];
  return fill(v !== undefined ? v : key, vars);
};

// ── ko'plik shakllari ──
// qiymat massiv bo'lsa: [1, 2-4, 5+] (rus uchun), bitta satr bo'lsa — barcha
// sonlarda bir xil (o'zbek va ingliz uchun yetarli)
const plural = (n, v, vars) => {
  const put = o => fill(v === undefined ? "" : v, { n, ...o });
  if (!Array.isArray(v)) return put(vars);
  if (cur === "ru") {
    // 1 klient / 2-4 klienta / 5+ klientov, 11-14 = ko'p shakl
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return fill(v[2], { n, ...vars });
    if (b === 1) return fill(v[0], { n, ...vars });
    if (b >= 2 && b <= 4) return fill(v[1], { n, ...vars });
    return fill(v[2], { n, ...vars });  }
  // o'zbek va ingliz: 1 boshqa hammasidan farq qiladi
  return fill(Math.abs(n) === 1 ? v[0] : v[v.length - 1], { n, ...vars });
};

// tp("kalit", 5) yoki tp("kalit", 3, { m: 12 }) — sonni hisobga olib shaklni tanlaydi
export const tp = (key, n, vars) => {
  const pack = DICT[cur] || uz;
  const v = pack[key] !== undefined ? pack[key] : uz[key];
  return plural(n, v, vars);
};

export const tArray = (key, vars) => {
  const pack = DICT[cur] || uz;
  const v = (pack[key] !== undefined ? pack[key] : uz[key]) || [];
  return Array.isArray(v) ? v : [v];
};

